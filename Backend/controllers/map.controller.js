module.exports.getAddress = async (req, res, next) => {
    const errors = validationResult(req);
    if (!errors.isEmpty()) {
        return res.status(400).json({ errors: errors.array() });
    }

    try {
        const address = await mapService.getAddressFromCoordinates(req.query.ltd, req.query.lng);
        res.status(200).json({ address });
    } catch (err) {
        res.status(404).json({ message: 'Address not found' });
    }
}

module.exports.getNearbyCaptains = async (req, res, next) => {
    const errors = validationResult(req);
    if (!errors.isEmpty()) {
        return res.status(400).json({ errors: errors.array() });
    }

    const nearby = await mapService.getCaptainsInTheRadius(Number(req.query.ltd), Number(req.query.lng), 5);

    // Only what the rider's map needs: where each cab is and what it is.
    res.status(200).json(nearby.map(({ captain, distanceKm }) => ({
        _id: captain._id,
        location: captain.location,
        vehicleType: captain.vehicle.vehicleType,
        distanceKm
    })));
}